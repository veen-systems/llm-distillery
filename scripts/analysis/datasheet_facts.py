#!/usr/bin/env python3
"""The countable half of a training dataset's DATASHEET.md (#178), generated from the split itself.

    python3 scripts/analysis/datasheet_facts.py --filter filters/human_thriving/v9 \
        --split datasets/training/human_thriving_v8_adj3 [--write filters/human_thriving/v9/DATASHEET.md]

Without --write it prints the block; with --write it replaces the text between the GENERATED markers of an
existing datasheet (it never creates one: the hand-written half is the part that needs a person).

RAISES rather than guessing:
  - the split fails training/split_validator.py (the one validator every reader runs)
  - the split's train/val row counts differ from the package's training_metadata.json, or it lacks those keys.
    ⚠️ A COUNT check only: it catches a wrong split of a different size, NOT a re-shuffle at the same sizes, and
    not two packages trained on one split (cultural_discovery v5 and v6 both record 6839/855). An id hash in
    training_metadata would make it an identity check (review 2026-10-21).
  - normalization.json has no stats.raw_min (the runtime op-point, CLAUDE.md "four places")

Every field the split does not record is printed as NOT RECORDED, never left out: a live split holds only
id/title/content/url/labels/dimension_names, so time window, language and per-row oracle provenance can only
come from a join upstream (scripts/analysis/split_prompt_lineage.py for the prompt).
"""
import argparse
import collections
import json
import statistics
import sys
import unicodedata
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts" / "gate"))
from training import split_validator as sv          # noqa: E402
import ground_truth_gate as gate                     # noqa: E402

BEGIN = "<!-- GENERATED by scripts/analysis/datasheet_facts.py: do not edit by hand -->"
END = "<!-- /GENERATED -->"
PARTS = ("train", "val", "test")
LENGTH_FLOOR = 300           # labelling-time floor (#93), make_oracle_prefilter
GN_HOST = "news.google.com"  # identified by URL host only, never by an id prefix (NM#310)


def latin_share(text):
    letters = [c for c in text if c.isalpha()]
    if not letters:
        return 1.0
    return sum("LATIN" in unicodedata.name(c, "") for c in letters) / len(letters)


def source_of(row_id):
    """The id's source part: everything before the trailing hash segment."""
    head, _, tail = row_id.rpartition("_")
    return head if head and len(tail) >= 8 else row_id


def facts(filter_dir, split_dir):
    filter_dir, split_dir = Path(filter_dir), Path(split_dir)
    spec = gate.load_scoring_spec(str(filter_dir / "config.yaml"))
    if spec is None:
        raise ValueError(f"{filter_dir}/config.yaml has no scoring spec")
    norm = json.loads((filter_dir / "normalization.json").read_text())
    op = (norm.get("stats") or {}).get("raw_min")
    if op is None:
        raise ValueError(f"{filter_dir}/normalization.json has no stats.raw_min")
    val = sv.validate_split_dir(split_dir, dims=list(spec["dims"]))
    meta = json.loads((filter_dir / "training_metadata.json").read_text())
    rows = {p: sv.read_jsonl(split_dir / f"{p}.jsonl") for p in PARTS if (split_dir / f"{p}.jsonl").exists()}
    for p, key in (("train", "train_examples"), ("val", "val_examples")):
        if key not in meta:
            raise ValueError(f"{filter_dir}/training_metadata.json has no {key}: cannot tie the split to the model")
        if len(rows.get(p, [])) != meta[key]:
            raise ValueError(f"{split_dir}/{p}.jsonl has {len(rows.get(p, []))} rows, but "
                             f"{filter_dir}/training_metadata.json says {key} = {meta[key]}: not this model's split")
    allrows = [r for p in rows for r in rows[p]]
    out = {"filter": str(filter_dir), "split": str(split_dir), "op": op, "parts": {},
           "trained_at_commit": meta.get("git_commit", "NOT RECORDED")}
    for p, rs in rows.items():
        scores = [gate.label_wa(r["labels"], spec, r["dimension_names"]) for r in rs]
        out["parts"][p] = {"rows": len(rs), "positive": sum(s >= op for s in scores),
                           "provenance_known": val[p]["provenance_known"],
                           "provenance_unknown": val[p]["provenance_unknown"]}
    lengths = sorted(len(r.get("content") or "") for r in allrows)
    hosts = collections.Counter(urlparse(r.get("url") or "").netloc.lower().removeprefix("www.") for r in allrows)
    sources = collections.Counter(source_of(r["id"]) for r in allrows)
    out.update(
        rows=len(allrows),
        length={"min": lengths[0], "median": int(statistics.median(lengths)), "below_floor": sum(n < LENGTH_FLOOR for n in lengths)},
        non_latin=sum(latin_share((r.get("title") or "") + " " + (r.get("content") or "")[:500]) < 0.5 for r in allrows),
        gn_rows=hosts.get(GN_HOST, 0), no_url=hosts.get("", 0),
        distinct_hosts=len(hosts), top_hosts=hosts.most_common(8),
        distinct_sources=len(sources), top_sources=sources.most_common(8),
        fields=sorted({k for r in allrows for k in r}),
    )
    return out


def render(f):
    pct = lambda a, b: f"{100 * a / b:.1f}%" if b else "n/a"
    L = [BEGIN, "", f"*Generated from `{f['split']}` against `{f['filter']}` (op-point {f['op']}, from "
         f"`normalization.json` stats.raw_min). Model trained at commit `{f['trained_at_commit'][:12]}`.*", "",
         "| split | rows | positive at op-point | provenance known / unknown |", "|---|---|---|---|"]
    for p, d in f["parts"].items():
        L.append(f"| {p} | {d['rows']:,} | {d['positive']:,} ({pct(d['positive'], d['rows'])}) | "
                 f"{d['provenance_known']:,} / {d['provenance_unknown']:,} |")
    n = f["rows"]
    L += ["",
          f"- **Fields each row carries:** {', '.join(f'`{k}`' for k in f['fields'])}. "
          f"**NOT RECORDED in the split:** publication date (so the time window), language, source type, "
          f"and per-row oracle provenance (model, prompt digest, date): see *How made*.",
          f"- **Content length (chars, as stored):** min {f['length']['min']:,}, median {f['length']['median']:,}; "
          f"{f['length']['below_floor']:,} rows below the {LENGTH_FLOOR}-char labelling floor (#93).",
          f"- **Mostly non-Latin script** (< 50% Latin letters in title + first 500 chars): {f['non_latin']:,} "
          f"rows ({pct(f['non_latin'], n)}).",
          f"- **Google News share: UNKNOWN.** Rows whose URL host is `{GN_HOST}`: {f['gn_rows']:,}, but this test "
          f"cannot see a Google News row whose URL was resolved to the publisher, and the split records no fetcher "
          f"or source type (NM#310), so a zero here is not evidence of none. Rows with no URL: {f['no_url']:,}.",
          f"- **Sources:** {f['distinct_sources']:,} distinct (id prefix), {f['distinct_hosts']:,} distinct URL hosts. "
          f"Top hosts: " + ", ".join(f"{h or '(none)'} {c:,}" for h, c in f["top_hosts"]) + ".",
          "", END]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--filter", required=True)
    ap.add_argument("--split", required=True)
    ap.add_argument("--write", help="an existing DATASHEET.md whose GENERATED block to replace")
    a = ap.parse_args()
    block = render(facts(a.filter, a.split))
    if not a.write:
        print(block)
        return
    p = Path(a.write)
    text = p.read_text(encoding="utf-8")
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise SystemExit(f"{p}: needs exactly one GENERATED block ({BEGIN!r} ... {END!r})")
    head, rest = text.split(BEGIN)
    _, tail = rest.split(END)
    p.write_text(head + block + tail, encoding="utf-8")
    print(f"wrote the generated block of {p}")


if __name__ == "__main__":
    main()
